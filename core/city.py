"""城市名归一化 — 统一各平台不同的城市文本格式"""
import re

_SUFFIXES = re.compile(r"[市省]+$")
_DISTRICT_SEP = re.compile(r"[·\-/\s]+")

_ALIAS_MAP = {
    "bj": "北京", "sh": "上海", "gz": "广州", "sz": "深圳",
    "hz": "杭州", "nj": "南京", "cd": "成都", "wh": "武汉",
    "cq": "重庆", "tj": "天津", "xa": "西安", "cs": "长沙",
    "北京市": "北京", "上海市": "上海", "天津市": "天津", "重庆市": "重庆",
    "广州市": "广州", "深圳市": "深圳", "杭州市": "杭州", "南京市": "南京",
    "成都市": "成都", "武汉市": "武汉", "西安市": "西安", "长沙市": "长沙",
    "苏州市": "苏州", "东莞市": "东莞", "佛山市": "佛山", "合肥市": "合肥",
    "郑州市": "郑州", "青岛市": "青岛", "大连市": "大连", "宁波市": "宁波",
    "厦门市": "厦门", "福州市": "福州", "济南市": "济南", "珠海市": "珠海",
    "无锡市": "无锡", "常州市": "常州", "昆明市": "昆明", "南昌市": "南昌",
    "沈阳市": "沈阳", "哈尔滨市": "哈尔滨", "长春市": "长春",
    "石家庄市": "石家庄", "太原市": "太原", "贵阳市": "贵阳",
    "南宁市": "南宁", "兰州市": "兰州", "海口市": "海口",
    "呼和浩特市": "呼和浩特", "乌鲁木齐市": "乌鲁木齐",
    "拉萨市": "拉萨", "银川市": "银川", "西宁市": "西宁",
}


def normalize_city(raw: str) -> str:
    """将各平台返回的城市文本归一化为纯市名。

    "深圳市" → "深圳"
    "深圳·南山区" → "深圳"
    "北京市朝阳区" → "北京"
    "广州 天河" → "广州"
    """
    if not raw:
        return ""
    text = raw.strip()
    if text in _ALIAS_MAP:
        return _ALIAS_MAP[text]

    base = _DISTRICT_SEP.split(text)[0]
    base = _SUFFIXES.sub("", base)

    if base in _ALIAS_MAP:
        return _ALIAS_MAP[base]

    for known in _ALIAS_MAP.values():
        if known in base:
            return known

    return base or text
