def all_cities() -> list[str]:
    """返回所有城市的扁平列表（去重）"""
    seen = set()
    result = []
    for c in HOT_CITIES:
        if c not in seen:
            seen.add(c)
            result.append(c)
    for prov_cities in CITIES_BY_PROVINCE.values():
        for c in prov_cities:
            if c not in seen:
                seen.add(c)
                result.append(c)
    return result
